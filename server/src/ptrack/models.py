"""Database tables.

Every synced table (project, item, comment) shares these conventions:
- `id` is a UUID generated by whichever device creates the row, so a phone can
  create tickets offline without asking the server for an id.
- `created_by` is the user who created it, set by the server.
- Rows are never removed. `deleted` is set instead, because other devices have
  to learn about a deletion through sync.

Who can see what: a user sees a project, its tickets and their comments if
they're a `Member` of the project (see auth.py and sync.py).

Timestamps are integers: milliseconds since the Unix epoch.
"""

from datetime import date, time
from enum import StrEnum

from sqlmodel import JSON, Column, Field, Index, SQLModel, UniqueConstraint


class ItemType(StrEnum):
    # Only tickets for now. The calendar is a view of tickets' due dates (D-026);
    # the column stays so other kinds of items can be added later.
    ticket = "ticket"


class Status(StrEnum):
    backlog = "backlog"
    todo = "todo"
    in_progress = "in_progress"
    blocked = "blocked"
    done = "done"


class Priority(StrEnum):
    none = "none"
    low = "low"
    medium = "medium"
    high = "high"
    urgent = "urgent"


class Role(StrEnum):
    owner = "owner"  # everything, incl. renaming/deleting the project, deleting tickets, managing members
    editor = "editor"  # create, edit and comment on tickets


# --- Accounts -----------------------------------------------------------------


class User(SQLModel, table=True):
    id: str = Field(primary_key=True)
    username: str = Field(unique=True, index=True)  # lowercase, used to sign in
    display_name: str = ""
    password_hash: str = ""  # see auth.hash_password; "" = can't sign in until a password is set
    is_admin: bool = False  # can create and manage accounts
    disabled: bool = False
    # Bumped whenever the user's project memberships change. A device that sees a
    # new epoch re-downloads everything, so it gains or loses projects correctly.
    epoch: int = 0
    created_at: int = 0


class DeviceToken(SQLModel, table=True):
    """One signed-in device. Only a hash of the token is stored."""

    id: str = Field(primary_key=True)
    user_id: str = Field(index=True)
    token_hash: str = Field(unique=True, index=True)
    name: str = ""  # e.g. "Pixel 8a" or "Firefox on Linux"
    created_at: int = 0
    last_used_at: int = 0
    revoked: bool = False


class Member(SQLModel, table=True):
    project_id: str = Field(primary_key=True)
    user_id: str = Field(primary_key=True, index=True)
    role: Role = Role.editor
    added_at: int = 0


# --- Synced data ------------------------------------------------------------------


class Project(SQLModel, table=True):
    id: str = Field(primary_key=True)
    created_by: str | None = None
    key: str = ""  # short prefix used in ticket keys, e.g. "HOME"; unique on the server
    name: str = ""
    next_number: int = 1  # number the next new ticket in this project gets
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class Item(SQLModel, table=True):
    """A ticket. Shows on the calendar on its due date."""

    id: str = Field(primary_key=True)
    created_by: str | None = None
    type: ItemType = ItemType.ticket
    project_id: str | None = Field(default=None, index=True)
    number: int | None = None  # assigned by the server; the 12 in HOME-12
    title: str = ""
    body: str = ""  # markdown
    status: Status = Status.todo
    priority: Priority = Priority.none
    labels: list[str] = Field(default_factory=list, sa_column=Column(JSON))
    due: date | None = None
    due_time: time | None = None  # optional, e.g. an exam at 10:00
    repeat: str | None = None  # recurrence rule, see recurrence.py
    next_id: str | None = None  # the copy created when this recurring ticket was done
    assignee_id: str | None = None  # a member of the project; None = unassigned
    assigned_on: date | None = None  # when it was handed to you; None = the day it was created
    completed_on: date | None = None  # set automatically when marked done; can be changed
    # When to remind the assignee (or the creator, if unassigned), relative to the
    # due date/time: "-8h", "-1d", "0". None = the default (see reminders.py); [] = none.
    reminders: list[str] | None = Field(default=None, sa_column=Column(JSON))
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class Comment(SQLModel, table=True):
    id: str = Field(primary_key=True)
    created_by: str | None = None
    item_id: str = Field(default="", index=True)
    body: str = ""
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class UserPrefs(SQLModel, table=True):
    """One person's preferences (see prefs.py). `id` is the user's id."""

    id: str = Field(primary_key=True)
    values: dict = Field(default_factory=dict, sa_column=Column(JSON))  # name → value; missing = default
    created_at: int = 0
    updated_at: int = 0


class Change(SQLModel, table=True):
    """One field edit: "set `field` of `entity_id` to `value` at `ts`, from `device_id`".

    This is the sync log and the history of every ticket. See sync.py.
    """

    __table_args__ = (
        # The same device can't make two edits to one field in the same millisecond,
        # so this identifies a change and lets retried uploads be ignored.
        UniqueConstraint("entity_id", "field", "ts", "device_id"),
        Index("ix_change_entity_field", "entity", "entity_id", "field"),
    )

    seq: int | None = Field(default=None, primary_key=True)  # server order; sync cursor
    project_id: str = Field(default="", index=True)  # whose members may see this change ("user:<id>" for prefs)
    user_id: str = ""  # who made it
    entity: str  # "project" | "item" | "comment"
    entity_id: str
    field: str
    value: str  # JSON-encoded
    ts: int
    device_id: str
