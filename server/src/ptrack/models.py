"""Database tables.

Every synced table shares three conventions:
- `id` is a UUID generated by whichever device creates the row, so a phone can
  create tickets offline without asking the server for an id.
- `owner_id` scopes rows to a user. There is one user for now; the column exists
  so multi-user later is a migration, not a rewrite.
- Rows are never removed. `deleted` is set instead, because other devices have
  to learn about a deletion through sync.

Timestamps are integers: milliseconds since the Unix epoch.
"""

from datetime import date
from enum import StrEnum

from sqlmodel import JSON, Column, Field, Index, SQLModel, UniqueConstraint


class ItemType(StrEnum):
    ticket = "ticket"
    event = "event"


class Status(StrEnum):
    backlog = "backlog"
    todo = "todo"
    in_progress = "in_progress"
    blocked = "blocked"
    done = "done"


class Priority(StrEnum):
    none = "none"
    low = "low"
    medium = "medium"
    high = "high"
    urgent = "urgent"


class Project(SQLModel, table=True):
    id: str = Field(primary_key=True)
    owner_id: str = Field(index=True)
    key: str = ""  # short prefix used in ticket keys, e.g. "HOME"
    name: str = ""
    next_number: int = 1  # number the next new ticket in this project gets
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class Item(SQLModel, table=True):
    """A ticket or a calendar event. Event-only fields arrive in Milestone 4."""

    id: str = Field(primary_key=True)
    owner_id: str = Field(index=True)
    type: ItemType = ItemType.ticket
    project_id: str | None = Field(default=None, index=True)
    number: int | None = None  # assigned by the server; the 12 in HOME-12
    title: str = ""
    body: str = ""  # markdown
    status: Status = Status.todo
    priority: Priority = Priority.none
    labels: list[str] = Field(default_factory=list, sa_column=Column(JSON))
    due: date | None = None
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class Comment(SQLModel, table=True):
    id: str = Field(primary_key=True)
    owner_id: str = Field(index=True)
    item_id: str = Field(default="", index=True)
    body: str = ""
    created_at: int = 0
    updated_at: int = 0
    deleted: bool = False


class Change(SQLModel, table=True):
    """One field edit: "set `field` of `entity_id` to `value` at `ts`, from `device_id`".

    This is the sync log and the history of every ticket. See sync.py.
    """

    __table_args__ = (
        # The same device can't make two edits to one field in the same millisecond,
        # so this identifies a change and lets retried uploads be ignored.
        UniqueConstraint("entity_id", "field", "ts", "device_id"),
        Index("ix_change_entity_field", "entity", "entity_id", "field"),
    )

    seq: int | None = Field(default=None, primary_key=True)  # server order; sync cursor
    owner_id: str = Field(index=True)
    entity: str  # "project" | "item" | "comment"
    entity_id: str
    field: str
    value: str  # JSON-encoded
    ts: int
    device_id: str
